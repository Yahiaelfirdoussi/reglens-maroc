"""Corpus statistics and OCR accuracy benchmark, rendered as ``docs/corpus.md``.

OCR accuracy cannot be measured on the scanned documents (no ground truth). Instead, documents
that have a native text layer are rendered to images and OCR'd with the production engine; the
native text is the reference. Rendered pages are cleaner than real scans, so the benchmark is
an optimistic bound on the scanned documents' accuracy.
"""

import statistics
import time
from collections import Counter
from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict, dataclass
from pathlib import Path

import pymupdf

from reglens.evaluation import text_metrics as tm
from reglens.ingestion.metadata import read_sidecar
from reglens.ingestion.ocr import DEFAULT_DPI, document_language, page_texts, tesseract_page


@dataclass(frozen=True)
class DocumentStats:
    file: str
    issuer: str
    text_source: str
    pages: int
    words: int
    has_reference: bool
    has_date: bool
    needs_review: bool
    year: int | None


def document_stats(raw_dir: Path) -> list[DocumentStats]:
    stats = []
    for pdf in sorted(raw_dir.rglob("*.pdf")):
        metadata = read_sidecar(pdf)
        texts = page_texts(pdf)
        stats.append(
            DocumentStats(
                file=pdf.relative_to(raw_dir).as_posix(),
                issuer=metadata.issuer,
                text_source=metadata.text_source or "unknown",
                pages=len(texts),
                words=sum(len(t.split()) for t in texts),
                has_reference=metadata.reference is not None,
                has_date=metadata.published is not None,
                needs_review=metadata.needs_review,
                year=metadata.published.year if metadata.published else None,
            )
        )
    return stats


@dataclass(frozen=True)
class OcrBenchmark:
    file: str
    language: str
    pages: int
    seconds: float
    char_edits: int
    chars: int
    word_edits: int
    words: int
    bag_f1: float
    numbers_found: int
    numbers: int

    @property
    def cer(self) -> float:
        return self.char_edits / max(self.chars, 1)

    @property
    def wer(self) -> float:
        return self.word_edits / max(self.words, 1)

    @property
    def number_recall(self) -> float:
        return self.numbers_found / max(self.numbers, 1)


def benchmark_document(
    pdf: Path, language: str | None = None, dpi: int = DEFAULT_DPI
) -> OcrBenchmark:
    """OCR a native-text PDF from its rendered images and compare with its text layer."""
    language = language or document_language(pdf)
    char_edits = chars = word_edits = words = found = numbers = 0
    f1_scores = []
    start = time.perf_counter()
    with pymupdf.open(pdf) as doc:
        pages = doc.page_count
        for page in doc:
            reference, hypothesis = page.get_text(), tesseract_page(page, language, dpi)
            if not reference.strip():
                continue
            e, n = tm.cer_counts(reference, hypothesis)
            char_edits, chars = char_edits + e, chars + n
            e, n = tm.wer_counts(reference, hypothesis)
            word_edits, words = word_edits + e, words + n
            e, n = tm.number_counts(reference, hypothesis, page_number=page.number + 1)
            found, numbers = found + e, numbers + n
            f1_scores.append(tm.bag_of_words_f1(reference, hypothesis))
    return OcrBenchmark(
        file=pdf.name,
        language=language,
        pages=pages,
        seconds=time.perf_counter() - start,
        char_edits=char_edits,
        chars=chars,
        word_edits=word_edits,
        words=words,
        bag_f1=statistics.fmean(f1_scores) if f1_scores else 0.0,
        numbers_found=found,
        numbers=numbers,
    )


def run_ocr_benchmark(raw_dir: Path, workers: int = 4) -> list[OcrBenchmark]:
    pdfs = [p for p in sorted(raw_dir.rglob("*.pdf")) if read_sidecar(p).text_source == "native"]
    with ProcessPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(benchmark_document, pdfs))


def render_markdown(stats: list[DocumentStats], benchmark: list[OcrBenchmark] | None) -> str:
    lines = ["# Corpus report", "", "Generated by `reglens corpus-report`.", ""]

    lines += ["## Corpus", "", "| Issuer | Documents | Pages | Words | Scanned (OCR) |"]
    lines += ["|---|---:|---:|---:|---:|"]
    for issuer in [*sorted({s.issuer for s in stats}), "**Total**"]:
        group = [s for s in stats if issuer == "**Total**" or s.issuer == issuer]
        scanned = sum(s.text_source == "ocr" for s in group)
        lines.append(
            f"| {issuer} | {len(group)} | {sum(s.pages for s in group)} | "
            f"{sum(s.words for s in group):,} | {scanned} ({scanned / len(group):.0%}) |"
        )
    pages = [s.pages for s in stats]
    years = sorted(s.year for s in stats if s.year)
    lines += [
        "",
        f"- Pages per document: median {statistics.median(pages):g}, max {max(pages)}.",
        f"- Publication years: {years[0]}–{years[-1]}"
        f" ({sum(y >= 2020 for y in years)} documents from 2020 onwards).",
        "",
        "## Metadata completeness",
        "",
        f"- Reference: {sum(s.has_reference for s in stats)}/{len(stats)}",
        f"- Publication date: {sum(s.has_date for s in stats)}/{len(stats)}",
        f"- Flagged `needs_review`: {sum(s.needs_review for s in stats)}",
    ]
    periods = Counter(f"{y // 5 * 5}–{y // 5 * 5 + 4}" for y in years)
    lines += ["", "| Period | Documents |", "|---|---:|"]
    lines += [f"| {period} | {count} |" for period, count in sorted(periods.items())]

    if benchmark:
        # The scanned corpus is French; other languages are reported but not aggregated
        # (the Arabic text layer stores glyphs in visual order, so it is a poor reference).
        french = [b for b in benchmark if b.language == "fra"]
        total = OcrBenchmark(
            file="**All French**",
            language="fra",
            pages=sum(b.pages for b in french),
            seconds=sum(b.seconds for b in french),
            char_edits=sum(b.char_edits for b in french),
            chars=sum(b.chars for b in french),
            word_edits=sum(b.word_edits for b in french),
            words=sum(b.words for b in french),
            bag_f1=statistics.fmean(b.bag_f1 for b in french) if french else 0.0,
            numbers_found=sum(b.numbers_found for b in french),
            numbers=sum(b.numbers for b in french),
        )
        lines += [
            "",
            "## OCR accuracy benchmark",
            "",
            "Native-text documents rendered at "
            f"{DEFAULT_DPI} dpi and OCR'd with the production engine (Tesseract CLI, each "
            "document's own language, column-aware); their text layer is the reference. Rendered "
            "pages are cleaner than real scans, so read these as an **optimistic bound** for "
            "the scanned documents.",
            "",
            "- **CER / WER**: character / word error rate (edit distance, whitespace-normalised).",
            "- **Bag-of-words F1**: word overlap ignoring order — high F1 with high WER means "
            "reading-order differences, not misread words.",
            "- **Number recall**: share of numbers and percentages (e.g. `100%`) recovered; "
            "the page's own number is excluded.",
            "- Non-French documents are listed but excluded from the total: the Arabic text "
            "layer stores glyphs in visual order, so it is not a reliable reference.",
            "",
            "| Document | Lang | Pages | CER | WER | BoW F1 | Number recall | s/page |",
            "|---|---|---:|---:|---:|---:|---:|---:|",
        ]
        ordered = sorted(benchmark, key=lambda b: (b.language != "fra", b.cer))
        for b in [*ordered, total]:
            lines.append(
                f"| {b.file[:55]} | {b.language} | {b.pages} | {b.cer:.1%} | {b.wer:.1%} | "
                f"{b.bag_f1:.3f} | "
                f"{b.number_recall:.1%} ({b.numbers_found}/{b.numbers}) | "
                f"{b.seconds / max(b.pages, 1):.1f} |"
            )
    return "\n".join(lines) + "\n"


def benchmark_as_dicts(benchmark: list[OcrBenchmark]) -> list[dict[str, object]]:
    return [
        {**asdict(b), "cer": b.cer, "wer": b.wer, "number_recall": b.number_recall}
        for b in benchmark
    ]
